/*  Level data. Each level is 15 rows of characters, one per 32x32 tile.
 *
 *    .  sky        =  stair block     <> pipe mouth
 *    #  ground     |  flagpole        [] pipe body
 *    ?  coin block F  flag
 *    b  brick      x  spent coin block
 *
 *  What the physics allows: a 3 tile climb (and only over a gap of 2 or less),
 *  a 4 tile gap flat out, and 2 clear rows above anything you expect to stand
 *  on. Coin blocks sit 5 rows above the floor — that is the only height his
 *  head reaches — but keep them away from the last few tiles before a gap or a
 *  climb: bumping one kills the jump, cutting 158px of reach down to 113px,
 *  and 84px if the block is 4 rows up. When in doubt run tools/check_levels.py,
 *  which plays the level to see if it can be finished and warns about this.
 */

