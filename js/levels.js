/* Turns the character rows into a flat Uint8Array plus the metadata the
 * engine needs (size in pixels, where the flagpole is, ...). */
function decodeLevel(def) {
  var rows = def.rows, h = rows.length, w = rows[0].length;
  var map = new Uint8Array(w * h), poleCol = -1, flagCol = -1;
  for (var y = 0; y < h; y++) {
    for (var x = 0; x < w; x++) {
      var t = TILE_FROM_CHAR[rows[y][x]];
      if (t === undefined) throw new Error('level ' + def.id + ': bad tile "' + rows[y][x] + '" at ' + x + ',' + y);
      map[y * w + x] = t;
      if (t === TILE.POLE && poleCol < 0) poleCol = x;
      if (t === TILE.FLAG) flagCol = x;
    }
  }
  return {
    id: def.id, name: def.name, blurb: def.blurb, time: def.time,
    spawn: def.spawn, map: map, cols: w, rows: h,
    width: w * 32, height: h * 32,
    poleCol: poleCol, poleX: poleCol * 32, flagCol: flagCol
  };
}
